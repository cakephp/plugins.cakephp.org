import { test, expect } from '@playwright/test'
import { execFileSync } from 'node:child_process'

const fixtures = mode => execFileSync('php', ['tests/browser/admin-state.php', mode], { encoding: 'utf8' })
const signIn = async (context, id = '1') => {
    const cookie = JSON.parse(fixtures(id))
    await context.addCookies([{ ...cookie, domain: '127.0.0.1', path: '/' }])
}

test.beforeEach(() => fixtures('reset'))
test.afterEach(() => fixtures('reset'))

test('existing login is reused and ordinary users cannot access admin', async ({ page, context }) => {
    await page.goto('/admin/users')
    await expect(page).toHaveURL(/\/?redirect=%2Fadmin%2Fusers/)
    await expect(page.getByText('Sign in', { exact: true })).toBeVisible()
    await signIn(context, '2')
    const response = await page.goto('/admin/users')
    expect(response.status()).toBe(403)
})

test('admin manages roles and suspension through the standard Interact endpoint', async ({ page, context }) => {
    await signIn(context)
    await page.goto('/admin/users')
    await expect(page.getByRole('navigation', { name: 'Admin navigation' })).toBeVisible()
    await page.screenshot({ path: 'tmp/admin-users-desktop.png', fullPage: true, animations: 'disabled' })
    await page.getByRole('searchbox', { name: 'Search users' }).fill('member')
    const row = page.locator('[data-user-id="2"]')
    await expect(row).toBeVisible()
    await expect(page.locator('[data-user-id="3"]')).toHaveCount(0)
    await row.getByRole('button', { name: 'Manage access' }).click()
    const dialog = page.getByRole('dialog')
    await expect(dialog).toBeVisible()
    await dialog.getByLabel('Role', { exact: true }).selectOption('admin')
    await dialog.getByLabel('Account active').uncheck()
    await dialog.getByRole('button', { name: 'Review change' }).click()
    const update = page.waitForResponse(response => response.url().endsWith('/_interact/update') && response.request().method() === 'POST')
    await dialog.getByRole('button', { name: 'Confirm change' }).click()
    expect((await update).status()).toBe(200)
    await expect(dialog).toHaveCount(0)
    await expect(row).toContainText('Admin')
    await expect(row).toContainText('Suspended')
    await row.getByRole('button', { name: 'Manage access' }).click()
    await dialog.getByLabel('Account active').check()
    await dialog.getByRole('button', { name: 'Review change' }).click()
    await dialog.getByRole('button', { name: 'Confirm change' }).click()
    await expect(row).toContainText('Active')
    await page.getByRole('link', { name: 'Sign out' }).click()
    await expect(page).toHaveURL('/')
    await page.goto('/admin/users')
    await expect(page).toHaveURL(/\/?redirect=%2Fadmin%2Fusers/)
})

test('featured editorial changes, preview and removal reach public cards', async ({ page, context }) => {
    await signIn(context)
    await page.goto('/admin/featured-plugins')
    const row = page.locator('[data-featured-id="1"]')
    await expect(page.getByRole('columnheader', { name: 'GitHub stars', exact: true })).toBeVisible()
    await expect(row.getByRole('cell', { name: '450', exact: true })).toBeVisible()
    await expect(row.getByRole('cell', { name: '5,000', exact: true })).toBeVisible()
    const listingId = await row.evaluate(element => element.closest('[data-interact-id]').dataset.interactId)
    await row.getByRole('button', { name: 'Edit', exact: true }).click()
    const dialog = page.getByRole('dialog')
    const editorId = await dialog.evaluate(element => element.closest('[data-interact-id]').dataset.interactId)
    expect(editorId).not.toBe(listingId)
    const previewResponses = []
    const trackPreview = response => {
        if (response.url().endsWith('/_interact/update')) previewResponses.push(response.json())
    }
    page.on('response', trackPreview)
    const preview = dialog.getByRole('region', { name: 'Card preview' })
    await dialog.getByLabel('Title override').fill('Community favourite')
    await expect(preview).toContainText('Community favourite')
    await dialog.getByLabel('Description override').fill('A curated description.')
    await expect(preview).toContainText('A curated description.')
    await dialog.getByLabel('Logo URL or path').fill('/img/cake.logo.svg')
    await expect(preview.locator('img')).toHaveAttribute('src', /^\/img\/cake\.logo\.svg(?:\?\d+)?$/)
    page.off('response', trackPreview)
    const previewUpdates = await Promise.all(previewResponses)
    expect(previewUpdates.length).toBeGreaterThanOrEqual(3)
    expect(previewUpdates.every(update => update.id === editorId)).toBe(true)
    await expect(dialog.getByRole('button', { name: 'Preview', exact: true })).toHaveCount(0)
    await expect(row).not.toContainText('Community favourite')
    await expect(dialog.locator('section + .modal-action').getByRole('button', { name: 'Save featured plugin' })).toHaveCount(1)
    await page.screenshot({ path: 'tmp/admin-featured-editor.png', fullPage: true, animations: 'disabled' })
    await dialog.getByRole('button', { name: 'Save featured plugin' }).click()
    await expect(dialog).toHaveCount(0)
    await expect(row).toContainText('Community favourite')
    await page.goto('/')
    await expect(page.locator('[data-featured-plugins]')).toContainText('Community favourite')
    await expect(page.locator('[data-featured-plugins]')).toContainText('A curated description.')
    await page.goto('/admin/featured-plugins')
    await row.getByRole('button', { name: 'Remove', exact: true }).click()
    await dialog.getByRole('button', { name: 'Confirm removal' }).click()
    await expect(row).toHaveCount(0)
})

