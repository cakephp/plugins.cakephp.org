test('featured columns sort in place and retain filters', async ({ page, context }) => {
    await signIn(context)
    await page.goto('/admin/featured-plugins')
    await page.evaluate(() => { window.adminSortMarker = 'retained' })
    const ids = () => page.locator('tbody tr').evaluateAll(rows => rows.map(row => row.dataset.featuredId))
    await page.getByRole('link', { name: /^GitHub stars/ }).click()
    await expect(page).toHaveURL(/sort=stars/)
    await expect.poll(ids).toEqual(['3', '1', '2'])
    await page.getByRole('link', { name: /^GitHub stars/ }).click()
    await expect(page).toHaveURL(/direction=desc/)
    await expect.poll(ids).toEqual(['2', '1', '3'])
    await page.getByRole('link', { name: /^Downloads/ }).click()
    await expect(page).toHaveURL(/sort=downloads/)
    await expect.poll(ids).toEqual(['1', '2', '3'])
    for (const [label, key] of [['Plugin', 'package'], ['Featured title', 'title'], ['Status', 'enabled']]) {
        await page.getByRole('columnheader').getByRole('link', { name: new RegExp(`^${label}`) }).click()
        if (key === 'package') {
            await expect(page).not.toHaveURL(/sort=/)
            await expect.poll(ids).toEqual(['2', '3', '1'])
        } else {
            await expect(page).toHaveURL(new RegExp(`sort=${key}`))
        }
    }
    await page.getByRole('combobox', { name: 'Filter by status' }).selectOption('enabled')
    await page.getByRole('link', { name: /^Downloads/ }).click()
    await expect(page).toHaveURL(/status=enabled/)
    await expect(page).toHaveURL(/sort=downloads/)
    expect(await page.evaluate(() => window.adminSortMarker)).toBe('retained')
})

test('mobile sidebar and theme preference work across admin and frontend', async ({ page, context }) => {
    const browserErrors = []
    page.on('pageerror', error => browserErrors.push(error.message))
    await signIn(context)
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto('/admin/users')
    await page.evaluate(() => { window.adminNavigationMarker = 'retained' })
    const toggle = page.getByRole('button', { name: 'Open navigation' })
    await toggle.focus()
    await page.keyboard.press('Enter')
    await expect(toggle).toHaveAttribute('aria-expanded', 'true')
    await expect(page.getByRole('navigation', { name: 'Admin navigation' })).toBeVisible()
    await page.screenshot({ path: 'tmp/admin-mobile-navigation.png', fullPage: true, animations: 'disabled' })
    await page.getByRole('link', { name: 'Featured plugins', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Featured plugins', exact: true })).toBeVisible()
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    await toggle.click()
    await expect(page.getByRole('link', { name: 'Featured plugins', exact: true })).toHaveAttribute('aria-current', 'page')
    await page.getByRole('link', { name: 'Users', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Users', exact: true })).toBeVisible()
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    await page.getByRole('button', { name: 'Toggle theme' }).click()
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'cakephp-dark')
    await toggle.click()
    await page.getByRole('link', { name: 'View site' }).click()
    await expect(page).toHaveURL('/')
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'cakephp-dark')
    expect(await page.evaluate(() => window.adminNavigationMarker)).toBe('retained')
    await page.goBack()
    await expect(page.getByRole('heading', { name: 'Users', exact: true })).toBeVisible()
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    await toggle.click()
    await expect(page.getByRole('link', { name: 'Users', exact: true })).toHaveAttribute('aria-current', 'page')
    await page.getByRole('link', { name: 'CakePHP Plugins', exact: true }).click()
    await expect(page).toHaveURL('/')
    expect(await page.evaluate(() => window.adminNavigationMarker)).toBe('retained')
    expect(browserErrors).toEqual([])
})
